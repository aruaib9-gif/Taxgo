const byKey = new Map(moduleGroups.map((g) => [g.key, g]));

// Sidebar rail order. `more` sits behind "Show more"; `divider` draws a rule after the group.
type RailEntry = { key: string; divider: boolean };
const resolveRail = (entries: RailEntry[]) => entries.map((e) => ({ ...e, group: byKey.get(e.key)! }));
export const railPrimary = resolveRail([{ key: "quick-entry", divider: true }, { key: "sales", divider: false }, { key: "purchasing", divider: true }, { key: "inventory", divider: false }, { key: "operations", divider: true }, { key: "accounting", divider: false }, { key: "finance", divider: true }]);
export const railMore = resolveRail([{ key: "crm", divider: false }, { key: "manufacturing", divider: false }, { key: "projects", divider: false }, { key: "human-resources", divider: false }, { key: "payroll", divider: true }, { key: "analytics", divider: true }, { key: "system", divider: false }]);

// Flat index of every routable page for lookups (breadcrumbs, titles, 404s). Sidebar labels win.
export const allNavItems: (NavItem & { group: string })[] = (() => {
  const seen = new Map<string, NavItem & { group: string }>();
  for (const g of moduleGroups) {
    for (const it of [...g.items, ...g.tiles]) {
      if (!seen.has(it.href)) seen.set(it.href, { label: it.label, href: it.href, icon: it.icon, group: g.label });
    }
  }
  return [...seen.values()];
})();

export function findNavItem(path: string) {
  const clean = "/" + path.replace(/^\/+|\/+$/g, "");
  return allNavItems.find((it) => it.href === clean);
}

// The group whose sidebar panel owns a path (exact match or a sub-route of one of its links).
export function groupForPath(path: string) {
  return moduleGroups.find((g) => g.items.some((it) => path === it.href || path.startsWith(it.href + "/")));
}
