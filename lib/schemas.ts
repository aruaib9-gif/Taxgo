// Schema-driven forms. Each entity maps a list route (href) to its collection,
// list columns and create-form fields. Fields mirror the source platform's forms.

export type FieldType =
  | "text"
  | "email"
  | "tel"
  | "number"
  | "money"
  | "date"
  | "textarea"
  | "select"
  | "checkbox"
  | "ref";

export type Field = {
  name: string;
  label: string;
  type: FieldType;
  options?: string[];
  required?: boolean;
  optional?: boolean;
  placeholder?: string;
  default?: string | number | boolean;
  section?: string;
  // for type "ref": pull options from another collection's records
  refCollection?: string;
  refLabel?: string; // which field on the referenced record to show (default: "name")
  refFallback?: string[]; // sample options shown even when the collection is empty
};

export type Column = { key: string; label: string; money?: boolean; badge?: boolean };

export type EntitySchema = {
  href: string;
  collection: string;
  title: string;
  subtitle?: string;
  newLabel: string;
  numberField?: { name: string; label: string; prefix: string };
  createHref?: string; // when set, "New" links to a full page instead of the modal
  tabs?: string[];
  columns: Column[];
  fields: Field[];
};

